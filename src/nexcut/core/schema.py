"""Parameter descriptor schema (MainApp.exe descriptor table) -- loader, value codec, validator.

``schema.json`` next to this module is generated by ``tools/gen_param_schema.py``
from the static descriptor arrays of MainApp.exe v0.0.0.52 (01 §0.2, 02 §2.2).
It carries all 1 001 *bound* descriptors (records whose value pointer targets the
global settings object, the ones persisted in the XML files) plus 147 *unbound*
descriptors (value pointer 0; controller-side ZF/process pages that are never
written to XML).

Each bound descriptor gives: owning table, section, ``Element.Attribute`` key,
``Lang/lang.txt`` label id, type code, default text, unit, min/max, enum option
label ids, a tag string and a unit class.

The schema also carries the *file layouts*: which descriptor tables are
registered to which XML file, in which order. The element/attribute order of a
file is the first-occurrence order of the descriptors (EVIDENCE: this rule
reproduces ``BkHardPara.xml``, ``BkManuPara.xml``, ``BkLayerPara.xml`` and
``1390backup.xml`` exactly -- see the generator docstring for the VAs).

The loader never touches the vendor package; it reads only ``schema.json``.
"""

from __future__ import annotations

