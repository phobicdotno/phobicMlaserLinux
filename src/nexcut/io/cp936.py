_DECODE: dict[int, str] = {}
_ENCODE: dict[str, bytes] = {}
for _code, _cp, _n in _EXTRA_DECODE_RUNS:
    for _i in range(_n):
        _b = (_code + _i).to_bytes(1 if _code < 0x100 else 2, "big")
        _DECODE[_code + _i] = chr(_cp + _i)
        _ENCODE[chr(_cp + _i)] = _b
for _cp, _code in _BEST_FIT.items():
    _ENCODE[chr(_cp)] = _code.to_bytes(1 if _code < 0x100 else 2, "big")
del _code, _cp, _n, _i, _b


def decode(data: bytes) -> str:
    """cp936 bytes -> str; bytes Windows cannot map survive as ``surrogateescape`` code points."""
    out: list[str] = []
    pos, n = 0, len(data)
    while pos < n:
        try:
            out.append(data[pos:].decode("gbk"))
            break
        except UnicodeDecodeError as exc:
            out.append(data[pos : pos + exc.start].decode("gbk"))
            at = pos + exc.start
            two = int.from_bytes(data[at : at + 2], "big") if at + 1 < n else -1
            if two in _DECODE:
                out.append(_DECODE[two])
                pos = at + 2
            elif data[at] in _DECODE:
                out.append(_DECODE[data[at]])
                pos = at + 1
            else:
                out.append(chr(0xDC00 + data[at]))  # surrogateescape
                pos = at + 1
    return "".join(out)


def encode(text: str) -> bytes:
    """str -> cp936 bytes like ``WideCharToMultiByte(936, 0, ...)``: GBK, extras, best fit, else ``?``.

    Code points U+DC80..U+DCFF (from :func:`decode`) are written back as the raw byte.
    UNVERIFIED: a character outside the BMP is one ``?`` here; Windows converts UTF-16
    code units and may emit ``??`` for the surrogate pair.
    """
    out = bytearray()
    for ch in text:
        o = ord(ch)
        if o < 0x80:
            out.append(o)
            continue
        if 0xDC80 <= o <= 0xDCFF:
            out.append(o - 0xDC00)
            continue
        try:
            out += ch.encode("gbk")
        except UnicodeEncodeError:
            out += _ENCODE.get(ch, DEFAULT_CHAR)
    return bytes(out)
